using System;
using System.Collections.Generic;
using System.IO;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEditor.Rendering;

namespace FS.Shaders.Editor
{
    /// <summary>Where a line of the processed shader came from.</summary>
    public enum ShaderLineOrigin
    {
        /// <summary>A line you wrote, in the shader file or the parent it inherits from.</summary>
        YourCode,

        /// <summary>A line inside a pass the processor generated from a template.</summary>
        Generated,

        /// <summary>
        /// A line the processor or the inheritance pre-pass added to code you wrote, such
        /// as tessellation code, CBUFFER entries or a rewritten include path.
        /// </summary>
        AddedByProcessor
    }

    /// <summary>The origin of one processed-shader line.</summary>
    public struct ShaderLineLocation
    {
        public ShaderLineOrigin Origin;

        /// <summary>Asset path of the file the line is in. Only set for YourCode.</summary>
        public string FilePath;

        /// <summary>1-based line in <see cref="FilePath"/>. Only set for YourCode.</summary>
        public int Line;

        /// <summary>
        /// Name of the pass the line sits in (the generated pass for Generated lines),
        /// or null when it's outside any pass, e.g. in HLSLINCLUDE.
        /// </summary>
        public string PassName;
    }

    /// <summary>
    /// Maps line numbers of the processed shader (the ones Unity's compiler messages
    /// use) back to the file you wrote. Built in three steps:
    ///   1. Find the generated passes. Every pass template starts with a comment header
    ///      containing "(Auto-generated by FreeSkies)", so a Pass block right under
    ///      such a header is generated and all its lines are Generated.
    ///   2. Diff the remaining lines against the shader file. For an inherited shader,
    ///      diff them against the merged source instead, then diff the merged source
    ///      against the parent file, and the lines the parent didn't claim against the
    ///      child file, so a line from the parent points into the parent.
    ///   3. Whatever is left unmatched was added by the processor.
    /// </summary>
    public class ShaderSourceMap
    {
        const string GENERATED_PASS_MARKER = "(Auto-generated by FreeSkies)";

        static readonly Regex s_passRegex = new Regex(ShaderParser.PassPattern, RegexOptions.Compiled);
        static readonly Regex s_passNameRegex = new Regex(@"Name\s*""([^""]+)""", RegexOptions.Compiled);

        // Index = processed line - 1
        ShaderLineLocation[] m_Lines;

        /// <summary>
        /// Build the map for one processed shader.
        /// </summary>
        /// <param name="processedSource">The processed text that was compiled.</param>
        /// <param name="shaderPath">Asset path of the shader file you wrote.</param>
        /// <param name="inheritResult">
        /// The inheritance result the processed text was built from. When it has a
        /// ParentPath, <see cref="ShaderInheritance.ResolveResult.Source"/> is the merged
        /// source that was processed.
        /// </param>
        public static ShaderSourceMap Build(string processedSource, string shaderPath,
            ShaderInheritance.ResolveResult inheritResult)
        {
            var map = new ShaderSourceMap();
            string[] processedLines = LineDiff.SplitLines(processedSource);
            map.m_Lines = new ShaderLineLocation[processedLines.Length];

            // Step 1: which pass each line sits in, and which passes are generated
            var passOfLine = new string[processedLines.Length];
            var isGenerated = new bool[processedLines.Length];
            MarkPasses(processedSource, processedLines, passOfLine, isGenerated);

            // Lines outside generated passes are what's left of the code you wrote
            var authoredIndices = new List<int>();
            var authoredLines = new List<string>();
            for (int i = 0; i < processedLines.Length; i++)
            {
                map.m_Lines[i].PassName = passOfLine[i];

                if (isGenerated[i])
                {
                    map.m_Lines[i].Origin = ShaderLineOrigin.Generated;
                    continue;
                }

                // Unmatched until step 2 says otherwise
                map.m_Lines[i].Origin = ShaderLineOrigin.AddedByProcessor;
                authoredIndices.Add(i);
                authoredLines.Add(processedLines[i]);
            }

            // Step 2: diff against what you wrote
            string[] shaderLines = LineDiff.SplitLines(ReadFile(shaderPath));
            if (inheritResult.ParentPath == null)
            {
                int[] toShader = LineDiff.Match(authoredLines.ToArray(), shaderLines);
                for (int k = 0; k < toShader.Length; k++)
                {
                    if (toShader[k] >= 0)
                        map.SetYourCode(authoredIndices[k], shaderPath, toShader[k]);
                }
            }
            else
            {
                MapThroughInheritance(map, authoredIndices, authoredLines.ToArray(),
                    inheritResult, shaderPath, shaderLines);
            }

            return map;
        }

        /// <summary>
        /// Where a processed line came from. False if the line is out of range.
        /// </summary>
        public bool TryLocate(int processedLine, out ShaderLineLocation location)
        {
            int index = processedLine - 1;
            if (m_Lines == null || index < 0 || index >= m_Lines.Length)
            {
                location = default;
                return false;
            }

            location = m_Lines[index];
            return true;
        }

        //=============================================================================
        // Compiler Messages
        //=============================================================================

        /// <summary>
        /// True if a compiler message's line is a line of the processed shader, as
        /// opposed to a line of an included file. Unity reports those with the shader's
        /// file name, or with no file at all.
        /// </summary>
        public static bool IsInProcessedShader(ShaderMessage message, string shaderPath)
        {
            if (string.IsNullOrEmpty(message.file))
                return true;
            return string.Equals(Path.GetFileName(message.file), Path.GetFileName(shaderPath),
                StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>
        /// One-line count of compiler messages by where they came from, e.g.
        /// "Your code: 0 errors, 4 warnings. Generated: 1 error (ShadowCaster), 5 warnings."
        /// Messages from included files count as your code. Messages with no line, or
        /// a line the map can't place, aren't counted.
        /// </summary>
        public static string Summarize(ShaderMessage[] messages, ShaderSourceMap map, string shaderPath)
        {
            int yourErrors = 0;
            int yourWarnings = 0;
            int generatedErrors = 0;
            int generatedWarnings = 0;
            var passesWithErrors = new List<string>();

            foreach (ShaderMessage message in messages)
            {
                if (message.line <= 0)
                    continue;

                bool isYourCode;
                string passName = null;
                if (!IsInProcessedShader(message, shaderPath))
                {
                    isYourCode = true;
                }
                else if (map != null && map.TryLocate(message.line, out ShaderLineLocation location))
                {
                    isYourCode = location.Origin == ShaderLineOrigin.YourCode;
                    passName = location.PassName;
                }
                else
                {
                    continue;
                }

                bool isError = message.severity == ShaderCompilerMessageSeverity.Error;
                if (isYourCode)
                {
                    if (isError) yourErrors++; else yourWarnings++;
                }
                else if (isError)
                {
                    generatedErrors++;
                    if (passName != null && !passesWithErrors.Contains(passName))
                        passesWithErrors.Add(passName);
                }
                else
                {
                    generatedWarnings++;
                }
            }

            string generatedPasses = passesWithErrors.Count > 0
                ? $" ({string.Join(", ", passesWithErrors)})"
                : "";
            return $"Your code: {Count(yourErrors, "error")}, {Count(yourWarnings, "warning")}. " +
                $"Generated: {Count(generatedErrors, "error")}{generatedPasses}, {Count(generatedWarnings, "warning")}.";
        }

        static string Count(int count, string noun)
        {
            return count == 1 ? $"1 {noun}" : $"{count} {noun}s";
        }

        //=============================================================================
        // Steps
        //=============================================================================

        static void MarkPasses(string source, string[] lines, string[] passOfLine, bool[] isGenerated)
        {
            int[] lineStarts = GetLineStarts(source);

            foreach (Match match in s_passRegex.Matches(source))
            {
                if (ShaderBlockUtility.IsInComment(source, match.Index))
                    continue;

                int end = ShaderSourceUtility.FindMatchingBrace(source, match.Index);
                if (end <= match.Index)
                    continue;

                int firstLine = LineOfIndex(lineStarts, match.Index);
                int lastLine = LineOfIndex(lineStarts, end - 1);

                var nameMatch = s_passNameRegex.Match(source, match.Index, end - match.Index);
                string passName = nameMatch.Success ? nameMatch.Groups[1].Value : "Unnamed pass";
                bool generated = HasGeneratedHeader(lines, firstLine);

                for (int i = firstLine; i <= lastLine && i < lines.Length; i++)
                {
                    passOfLine[i] = passName;
                    isGenerated[i] = generated;
                }
            }
        }

        /// <summary>
        /// True if the comment lines right above the pass's first line contain the
        /// template header marker.
        /// </summary>
        static bool HasGeneratedHeader(string[] lines, int passFirstLine)
        {
            for (int i = passFirstLine - 1; i >= 0; i--)
            {
                string trimmed = lines[i].Trim();
                if (!trimmed.StartsWith("//"))
                    return false;
                if (trimmed.Contains(GENERATED_PASS_MARKER))
                    return true;
            }
            return false;
        }

        static void MapThroughInheritance(ShaderSourceMap map, List<int> authoredIndices,
            string[] authoredLines, ShaderInheritance.ResolveResult inheritResult,
            string childPath, string[] childLines)
        {
            string[] mergedLines = LineDiff.SplitLines(inheritResult.Source);
            string[] parentLines = LineDiff.SplitLines(ReadFile(inheritResult.ParentPath));

            int[] toMerged = LineDiff.Match(authoredLines, mergedLines);
            int[] mergedToParent = LineDiff.Match(mergedLines, parentLines);

            // Only diff the merged lines the parent didn't claim against the child.
            // Diffing all of them would let the child's braces and ENDHLSLs pair up with
            // the parent's and leave real child lines unmatched.
            var unclaimedIndices = new List<int>();
            var unclaimedLines = new List<string>();
            for (int i = 0; i < mergedLines.Length; i++)
            {
                if (mergedToParent[i] < 0)
                {
                    unclaimedIndices.Add(i);
                    unclaimedLines.Add(mergedLines[i]);
                }
            }

            int[] unclaimedToChild = LineDiff.Match(unclaimedLines.ToArray(), childLines);
            var mergedToChild = new int[mergedLines.Length];
            for (int i = 0; i < mergedToChild.Length; i++)
                mergedToChild[i] = -1;
            for (int k = 0; k < unclaimedToChild.Length; k++)
                mergedToChild[unclaimedIndices[k]] = unclaimedToChild[k];

            for (int k = 0; k < toMerged.Length; k++)
            {
                int merged = toMerged[k];
                if (merged < 0)
                    continue;

                if (mergedToParent[merged] >= 0)
                    map.SetYourCode(authoredIndices[k], inheritResult.ParentPath, mergedToParent[merged]);
                else if (mergedToChild[merged] >= 0)
                    map.SetYourCode(authoredIndices[k], childPath, mergedToChild[merged]);
            }
        }

        //=============================================================================
        // Helpers
        //=============================================================================

        void SetYourCode(int processedIndex, string filePath, int fileLineIndex)
        {
            m_Lines[processedIndex].Origin = ShaderLineOrigin.YourCode;
            m_Lines[processedIndex].FilePath = filePath;
            m_Lines[processedIndex].Line = fileLineIndex + 1;
        }

        static string ReadFile(string path)
        {
            if (string.IsNullOrEmpty(path) || !File.Exists(path))
                return "";
            return File.ReadAllText(path);
        }

        /// <summary>Character index where each line starts, counting LF only.</summary>
        static int[] GetLineStarts(string source)
        {
            var starts = new List<int> { 0 };
            for (int i = 0; i < source.Length; i++)
            {
                if (source[i] == '\n')
                    starts.Add(i + 1);
            }
            return starts.ToArray();
        }

        /// <summary>0-based line containing a character index.</summary>
        static int LineOfIndex(int[] lineStarts, int index)
        {
            int found = Array.BinarySearch(lineStarts, index);
            return found >= 0 ? found : ~found - 1;
        }
    }
}
